def net_benefit(y_true, proba, threshold):
    preds = (proba >= threshold).astype(int)
    tp = ((preds == 1) & (y_true == 1)).sum()
    fp = ((preds == 1) & (y_true == 0)).sum()
    n = len(y_true)
    odds = threshold / (1.0 - threshold)
    return (tp / n) - (fp / n) * odds

